// Generates examples/documents.js: sample documents parsed by the segmsh processors.
// Also copies the built editor next to the pages, so they work from any server root.
// Run with `npm run examples`.
import { copyFileSync, writeFileSync } from "node:fs";
import HtmlProcessor from "@segmsh/html";
import MdProcessor from "@segmsh/md";
import JsonProcessor from "@segmsh/json";
import TomlProcessor from "@segmsh/toml";

const markdown = `---
title: Getting started
description: Install the CLI and translate your first file
---

# Getting started

Segm.sh splits documents into **segments** so they can be translated *without* touching the markup.
Read the [installation guide](https://segm.sh/docs/install) first.

## Install

1. Install Node.js 20 or newer.
2. Run \`npm install -g segmsh\` in your terminal.
3. Check the version with \`segmsh --version\`.

> Tip: segments keep inline formatting as markers, like **bold** or [links](https://segm.sh).

| Format | Processor |
| ------ | --------- |
| Markdown | @segmsh/md |
| HTML | @segmsh/html |

![Segm.sh logo](data:image/svg+xml;base64,PHN2ZyB4bWxucz0iaHR0cDovL3d3dy53My5vcmcvMjAwMC9zdmciIHdpZHRoPSIxMjAiIGhlaWdodD0iMzIiPjxyZWN0IHdpZHRoPSIxMjAiIGhlaWdodD0iMzIiIHJ4PSI2IiBmaWxsPSIjMmY2ZmRlIi8+PHRleHQgeD0iNjAiIHk9IjIxIiBmaWxsPSIjZmZmIiBmb250LWZhbWlseT0ic2Fucy1zZXJpZiIgZm9udC1zaXplPSIxNCIgdGV4dC1hbmNob3I9Im1pZGRsZSI+U2VnbS5zaDwvdGV4dD48L3N2Zz4=)

That's it — you're ready to translate.
`;

const html = `<!doctype html>
<html>
<head><title>Pricing</title></head>
<body>
  <h1>Simple, <em>transparent</em> pricing</h1>
  <p>Start for free and upgrade when your team grows. <a href="/contact">Contact sales</a> for volume discounts.</p>
  <ul>
    <li>Unlimited projects</li>
    <li>Up to <strong>5</strong> team members</li>
    <li>Email support</li>
  </ul>
  <button>Start free trial</button>
  <script>console.log("never rendered")</script>
</body>
</html>`;

const json = JSON.stringify({
  app: { title: "Inbox", empty: "No messages yet" },
  actions: { send: "Send", archive: "Archive", delete: "Delete permanently" },
  errors: { offline: "You are offline. Messages will be sent when the connection is back." },
}, null, 2);

const toml = `[menu]
file = "File"
edit = "Edit"
quit = "Quit the application"

[dialog]
confirm = "Are you sure you want to discard your changes?"
`;

const documents = {
  markdown: new MdProcessor().parse(markdown),
  html: new HtmlProcessor().parse(html),
  json: new JsonProcessor().parse(json),
  toml: new TomlProcessor().parse(toml),
};

// Pseudo-translation: accented, ~40% longer, markers untouched
const ACCENTS = { a: "á", e: "é", i: "í", o: "ó", u: "ú", c: "ç", n: "ñ", s: "š", y: "ý", A: "Á", E: "É", O: "Ó", S: "Š" };
const pseudo = (text) => {
  const accented = text.replace(/(\{\/?[a-zA-Z][a-zA-Z0-9-]*?\d+\})|[a-zA-Z]/g, (match, marker) =>
    marker ? marker : ACCENTS[match] ?? match);
  const plain = text.replace(/\{[^}]*\}/g, "");
  return accented + (plain.length > 12 ? " ·" + " lóřém".repeat(Math.ceil(plain.length / 15)) : "");
};

// Every third segment stays untranslated (same text as the source)
const translated = Object.fromEntries(
  Object.entries(documents).map(([name, doc]) => [
    name,
    {
      ...doc,
      segments: doc.segments.map((segment, index) =>
        index % 3 === 2 ? segment : { ...segment, text: pseudo(segment.text) }),
    },
  ]),
);

writeFileSync(
  new URL("./documents.js", import.meta.url),
  `// Generated by documents.mjs\nwindow.SAMPLE_DOCUMENTS = ${JSON.stringify(documents)};\nwindow.SAMPLE_TRANSLATIONS = ${JSON.stringify(translated)};\n`,
);

for (const file of ["segmsh-editor.min.js", "editor.css"]) {
  copyFileSync(new URL(`../dist/${file}`, import.meta.url), new URL(`./${file}`, import.meta.url));
}
